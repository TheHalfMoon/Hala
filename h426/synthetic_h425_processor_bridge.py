"""H426 invented GUI sample -> exact frozen H425 Qwen drag input bridge.

Only processes images freshly generated by the first-party synthetic builder.
No external source ZIP, pretrained weights, private images, GPU or training.
These generated cases are deliberately NOT admitted to H199 original TRAIN.
"""
from __future__ import annotations

import hashlib
import io
import json

from PIL import Image

from h426.h425_loss_bridge import (
    H425_SOURCE, _load_source_module, source_case_identity,
)
from h426.synthetic_drag_curriculum import (
    DOMAINS, HEIGHT, SCHEMA, WIDTH, generate,
)

LANGUAGES = ("en", "ar")
H425_PROCESSOR_IMAGE_MAX = (640, 400)


def pack_generated(split: str, index: int, domain: str, language: str):
    """Build the authentic H425 resized-image/prompt/JSON target contract.

    H425's source_image() keeps native WIDTH/HEIGHT for ground truth but
    resizes its actual image processor input with LANCZOS to <= 640x400.
    A successful pure-Python packing is NOT a Qwen processor/model pass.
    """
    if language not in LANGUAGES or type(language) is not str:
        raise ValueError("H426 invented sample language must be en/ar")
    if domain not in DOMAINS or type(domain) is not str:
        raise ValueError("H426 invented sample domain unknown")
    sample = generate(split, index, domain)
    if sample.get("schema") != SCHEMA or sample.get("split") != split:
        raise ValueError("H426 synthetic source schema or split drift")
    raw = sample["original_png_bytes"]
    if (type(raw) is not bytes
        or hashlib.sha256(raw).hexdigest() != sample["image_sha256"]):
        raise ValueError("H426 invented PNG byte provenance drift")
    with Image.open(io.BytesIO(raw)) as png:
        if (png.format != "PNG" or png.mode != "RGB"
            or png.size != (WIDTH, HEIGHT)):
            raise ValueError("H426 synthetic original RGB PNG geometry drift")
        image = png.convert("RGB")
    image.thumbnail(H425_PROCESSOR_IMAGE_MAX, Image.Resampling.LANCZOS)
    if image.size != (600, 400):
        raise ValueError("H426 synthetic H425 processor image resize drift")
    rows = sample["actions"]
    if (len(rows) != 2 or tuple(row["language"] for row in rows) != LANGUAGES
        or len({row["id"] for row in rows}) != 2):
        raise ValueError("H426 synthetic bilingual source pairing drift")
    row = rows[LANGUAGES.index(language)]
    if (row["domain"] != domain
        or row["image_sha256"] != sample["image_sha256"]
        or row["source_role"] != "firstparty_generated_synthetic_research_not_admitted"
        or row["family"] != sample["family"]):
        raise ValueError("H426 invented screenshot source role/provenance drift")
    # Source H425 helper functions are frozen, not approximated/reimplemented.
    h425 = _load_source_module("h426_pack_h425_frozen", H425_SOURCE)
    normalized = h425.target({
        "start": row["start"], "end": row["end"],
        "ordered": row["target"]["ordered"],
    }, WIDTH, HEIGHT)
    if normalized != row["target"]:
        raise ValueError("H426 invented native coordinate target differs from H425")
    source_id = source_case_identity(row)
    answer = json.dumps(normalized, separators=(",", ":"), ensure_ascii=False)
    request = h425.prompt(row)
    if (not request.startswith(row["body"] + "\n")
        or not 1 <= len(request) <= 4096 or not answer.startswith('{"type":"drag"')):
        raise ValueError("H426 original H425 prompt/completion contract drift")
    return {
        "image": image,
        "request": request,
        "answer": answer,
        "domain": domain,
        "language": language,
        "split": split,
        "family": sample["family"],
        "source_sha256": sample["image_sha256"],
        "source_case_identity_sha256": source_id["id_sha256"],
        "source_is_admitted_to_train": False,
        "new_model_trained": False,
    }


def check_generated_with_real_processor(processor, split, index, domain, language):
    """Call existing H426 full vision-token/pixel supervision validator.

    This is a CPU processor task, not a Qwen model forward or optimizer.
    Returns metrics only; no synthetic image bytes, target JSON or prompt.
    """
    from h426.full_processor_contract import check
    sample = pack_generated(split, index, domain, language)
    proof = check(processor, sample["image"], sample["request"],
                  sample["answer"], sample["domain"])
    return {
        **proof, "split": split, "domain": domain, "language": language,
        "synthetic_source_image_sha256": sample["source_sha256"],
        "synthetic_source_family": sample["family"],
        "source_is_admitted_to_train": False,
    }
