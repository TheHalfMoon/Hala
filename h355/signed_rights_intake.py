"""H355 independent rights-decision signature intake (inert by default).

A signed independent review is NOT a legal opinion proof by itself,
nor authority to activate H199 training, score OOD or release Hala.
No external reviewer trusted yet: the production registry is EMPTY.
No cryptographic key, signature or privately authored approval is
ever autogenerated in the shipped implementation.
"""
from __future__ import annotations

from base64 import b64decode
from datetime import date, datetime, timedelta, timezone
from hashlib import sha256
import json
from pathlib import Path
import re
from types import MappingProxyType

from h343.independent_rights_review_request import (
    build_public_review_request, FAMILIES,
)

ROLE = "H355_EXTERNAL_SIGNATURE_VERIFICATION_ONLY_NO_TRAIN_ADMISSION"
SCHEMA = "hala.external-screenshot-rights-review.v1"
ENVELOPE_SCHEMA = "hala.external-screenshot-rights-signed-envelope.v1"
MAX_BYTES = 16384
# TRUST IS A SEPARATE, EXPLICIT INDEPENDENT GOVERNANCE DECISION.
# A candidate-supplied public key MUST NEVER be accepted as a trust anchor.
# No key is enrolled in the currently qualified production source.
TRUSTED_REVIEWERS = MappingProxyType({})
DIGEST = re.compile(r"[0-9a-f]{64}\Z")


def require(ok: bool) -> None:
    if not ok:
        raise ValueError("H355_INDEPENDENT_RIGHTS_REVIEW_NOT_AUTHENTICATED")


def canonical(value) -> bytes:
    try:
        raw = json.dumps(value, ensure_ascii=True, sort_keys=True,
                         separators=(",", ":"), allow_nan=False).encode("ascii")
    except (TypeError, ValueError, UnicodeError):
        raise ValueError("H355_INDEPENDENT_RIGHTS_REVIEW_NOT_AUTHENTICATED") from None
    require(0 < len(raw) <= MAX_BYTES)
    return raw


def unique_object(items):
    data = {}
    for key, value in items:
        require(key not in data)
        data[key] = value
    return data


def nonfinite(_):
    raise ValueError("H355_INDEPENDENT_RIGHTS_REVIEW_NOT_AUTHENTICATED")


def read_envelope(raw: bytes) -> dict:
    require(type(raw) is bytes and 32 <= len(raw) <= MAX_BYTES)
    try:
        doc = json.loads(raw.decode("utf-8"), object_pairs_hook=unique_object,
                         parse_constant=nonfinite)
    except (ValueError, UnicodeError, TypeError, RecursionError):
        raise ValueError("H355_INDEPENDENT_RIGHTS_REVIEW_NOT_AUTHENTICATED") from None
    require(type(doc) is dict and set(doc) == {
        "schema", "key_id", "payload", "signature_b64"})
    require(doc["schema"] == ENVELOPE_SCHEMA
            and type(doc["key_id"]) is str and DIGEST.fullmatch(doc["key_id"])
            and type(doc["signature_b64"]) is str
            and len(doc["signature_b64"]) == 88
            and type(doc["payload"]) is dict)
    return doc


def _utc_date(text: object) -> date:
    require(type(text) is str and re.fullmatch(r"\d{4}-\d{2}-\d{2}", text))
    try:
        parsed = date.fromisoformat(text)
    except ValueError:
        raise ValueError("H355_INDEPENDENT_RIGHTS_REVIEW_NOT_AUTHENTICATED") from None
    require(parsed.isoformat() == text)
    return parsed


def verify_signed_review(raw: bytes, root: Path) -> dict:
    """Verify ONLY authenticity/scope. Never change training allowlists.

    Production has ZERO trusted key IDs. Unit tests may temporarily patch
    that registry with invented, memory-only keys to test this verifier.
    """
    document = read_envelope(raw)
    payload = document["payload"]
    require(set(payload) == {
        "schema", "review_request_sha256", "reviewer_identity",
        "reviewer_independence_evidence_sha256", "evidence_custody_sha256",
        "signed_date_utc", "expiry_date_utc", "reviewed_families",
        "review_scope"})
    require(payload["schema"] == SCHEMA)
    request = build_public_review_request(root)
    require(payload["review_request_sha256"] == request["request_sha256"])
    require(type(payload["reviewer_identity"]) is str
            and 8 <= len(payload["reviewer_identity"]) <= 160
            and all(ord(ch) >= 32 for ch in payload["reviewer_identity"]))
    for key in ("reviewer_independence_evidence_sha256",
                "evidence_custody_sha256"):
        require(type(payload[key]) is str and DIGEST.fullmatch(payload[key]))
    issued = _utc_date(payload["signed_date_utc"])
    expires = _utc_date(payload["expiry_date_utc"])
    # Signed *_utc fields must be checked against the UTC calendar day,
    # not the host's local timezone (which can differ near midnight).
    now = datetime.now(timezone.utc).date()
    require(issued <= now <= expires
            and timedelta(days=1) <= expires - issued <= timedelta(days=365))
    scope = payload["review_scope"]
    require(type(scope) is dict and set(scope) == {
        "purpose", "commercial_use", "output_weight_distribution",
        "training_use", "third_party_asset_exclusions"})
    require(scope["purpose"] == "rendered_gui_screenshot_vision_model"
            and type(scope["commercial_use"]) is bool
            and type(scope["output_weight_distribution"]) is bool
            and type(scope["training_use"]) is bool
            and scope["third_party_asset_exclusions"] is True)
    families = payload["reviewed_families"]
    require(type(families) is list and len(families) == len(FAMILIES))
    expected = request["families"]
    for original, reviewed in zip(expected, families):
        require(type(reviewed) is dict and set(reviewed) == {
            "family", "source_git_blob", "source_introduction_commit",
            "copyright_title_evidence_sha256",
            "rendered_screenshot_rights_granted", "derivative_weights_granted",
            "reviewer_title_confirmed", "license_restrictions_resolved"})
        require(reviewed["family"] == original["family"]
                and reviewed["source_git_blob"] == original["pinned_git_blob"]
                and reviewed["source_introduction_commit"] ==
                    original["introducing_commit"]
                and type(reviewed["copyright_title_evidence_sha256"]) is str
                and DIGEST.fullmatch(reviewed["copyright_title_evidence_sha256"]))
        for key in ("rendered_screenshot_rights_granted",
                    "derivative_weights_granted", "reviewer_title_confirmed",
                    "license_restrictions_resolved"):
            require(type(reviewed[key]) is bool)
    # Identity is tied to a trusted, code-reviewed *external* public key.
    # A submitted key inside the envelope is never considered trust.
    key_id = document["key_id"]
    require(key_id in TRUSTED_REVIEWERS)
    registered = TRUSTED_REVIEWERS[key_id]
    require(type(registered) is dict and set(registered) ==
            {"identity", "public_key_bytes"}
            and registered["identity"] == payload["reviewer_identity"]
            and type(registered["public_key_bytes"]) is bytes
            and len(registered["public_key_bytes"]) == 32
            and sha256(registered["public_key_bytes"]).hexdigest() == key_id)
    try:
        signature = b64decode(document["signature_b64"], validate=True)
        require(len(signature) == 64)
        from cryptography.hazmat.primitives.asymmetric.ed25519 import (
            Ed25519PublicKey,
        )
        Ed25519PublicKey.from_public_bytes(
            registered["public_key_bytes"]).verify(signature,
                                                  canonical(payload))
    except (ValueError, TypeError, ImportError):
        raise ValueError("H355_INDEPENDENT_RIGHTS_REVIEW_NOT_AUTHENTICATED") from None
    except Exception as exc:
        # Ed25519 InvalidSignature; never expose private input details.
        if exc.__class__.__name__ != "InvalidSignature":
            raise
        raise ValueError("H355_INDEPENDENT_RIGHTS_REVIEW_NOT_AUTHENTICATED") from None
    all_grants = all(all(f[key] for key in (
        "rendered_screenshot_rights_granted",
        "derivative_weights_granted", "reviewer_title_confirmed",
        "license_restrictions_resolved")) for f in families)
    reviewed_scope = (all_grants and scope["training_use"]
                      and scope["output_weight_distribution"])
    return {
        "role": ROLE, "external_signature_verified": True,
        "request_sha256": request["request_sha256"],
        "source_family_count": len(families),
        "specified_training_scope_reviewed": reviewed_scope,
        "commercial_scope_covered": bool(reviewed_scope and scope["commercial_use"]),
        "independence_and_title_require_human_audit": True,
        "source_disjoint_blind_ood": False,
        "official_h199_train_admitted": False,
        "can_train": False, "can_release": False,
    }
